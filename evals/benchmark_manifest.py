def suite_stats(task_dir: Path) -> dict | None:
    specs = [json.loads(p.read_text()) for p in sorted(task_dir.glob("*.json"))]
    if not specs:
        return None
    sizes, files, multi, over4k = [], [], 0, 0
    for spec in specs:
        fixture = ROOT / spec["fixture"]
        py = [p for p in fixture.rglob("*.py") if "__pycache__" not in p.parts]
        sizes.append(sum(p.stat().st_size for p in py))
        files.append(len(py))
        if len(spec.get("ground_truth_files", [])) > 1:
            multi += 1
        if any(p.stat().st_size > 4000 for p in py):
            over4k += 1
    return {
        "n": len(specs),
        "specs": specs,
        "median_bytes": int(statistics.median(sizes)),
        "max_bytes": max(sizes),
        "median_files": int(statistics.median(files)),
        "multi_file_gt": multi,
        "has_file_over_4k": over4k,
    }


def render() -> str:
    lines = [
        "# The SmallCoder benchmark",
        "",
        "<!-- GENERATED by `python -m evals.benchmark_manifest` — do not edit by hand. -->",
        "",
        "Every suite below meets one validation contract, enforced by",
        "`tests/` with zero model involvement: the fixture's own pytest suite",
        "**fails** at baseline, applying **only** the declared reference fix makes it",
        "**pass**, every reference anchor matches exactly once, committed fixtures are",
        "never mutated by validation (checked by digest), and task ids are unique",
        "across the whole repository.",
        "",
        "Difficulty is characterized here by **objective proxies only** (size, file",
        "count, whether reads must be paged). No frontier-model ceiling has been",
        "measured yet; until one is, a 0-solve task cannot be distinguished from an",
        "impossible one. That is a stated gap, not an oversight.",
        "",
    ]
    total = 0
    rows = []
    details = []
    for suite in SUITES:
        stats = suite_stats(ROOT / suite["tasks"])
        if stats is None:
            continue
        total += stats["n"]
        rows.append(
            f"| {suite['name']} | {stats['n']} | {stats['median_bytes']:,} B "
            f"| {stats['median_files']} | {stats['multi_file_gt']} "
            f"| {stats['has_file_over_4k']} |"
        )
        details += [
            f"## {suite['name']} — {stats['n']} tasks",
            "",
            f"- **Provenance:** {suite['provenance']}",
            f"- **Contamination:** {suite['contamination']}",
            f"- **Role:** {suite['role']}",
            f"- **Size:** median {stats['median_bytes']:,} B (max {stats['max_bytes']:,} B) "
            f"across a median of {stats['median_files']} Python files; "
            f"{stats['multi_file_gt']} task(s) need more than one ground-truth file; "
            f"{stats['has_file_over_4k']} contain a file over 4,000 B "
            "(forcing paged reads under the agent's output truncation).",
            "",
        ]
        if suite["name"] == "realbugs":
            details.append("| task | repo | fix merged | upstream commit |")
            details.append("| --- | --- | --- | --- |")
            for spec in stats["specs"]:
                prov = spec.get("provenance", {})
                details.append(
                    f"| {spec['id']} | {prov.get('repo', '?')} | {prov.get('fix_date', '?')} "
                    f"| `{prov.get('fix_commit', '?')[:12]}` |"
                )
            details.append("")
    lines += [
        f"**{total} tasks** across {len(rows)} suites:",
        "",
        "| suite | tasks | median size | median .py files | multi-file GT | files >4KB |",
        "| --- | --- | --- | --- | --- | --- |",
        *rows,
        "",
        *details,
        "## Licensing",
        "",
        "Suites `design`, `heldout`, `m3_generalization` and `ladder` were written",
        "for this repository (MIT, see [LICENSE](LICENSE)). `quixbugs` derives from",
        "[QuixBugs](https://github.com/jkoppel/QuixBugs) (MIT) — see",
        "[evals/quixbugs/ATTRIBUTION.md](evals/quixbugs/ATTRIBUTION.md). `realbugs`",
        "snapshots real repositories at a pre-fix commit; each snapshot retains its",
        "upstream LICENSE/NOTICE files, and per-task provenance (repo, commit, date,",
        "subject) is recorded in the task spec and in",
        "[evals/realbugs/ATTRIBUTION.md](evals/realbugs/ATTRIBUTION.md).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m evals.benchmark_manifest")
    parser.add_argument("--check", action="store_true",
                        help="fail if BENCHMARK.md does not match the repository state")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text() if OUT.is_file() else ""
        if current != text:
            print("BENCHMARK.md is stale; run `python -m evals.benchmark_manifest`",
                  file=sys.stderr)
            return 1
        print("BENCHMARK.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Generate BENCHMARK.md — the manifest of every suite in this repository.

A benchmark you cannot audit is a rumor. This module derives the manifest from
the task specs and fixtures actually on disk, so counts, sizes, provenance and
licensing can never drift from reality: regenerate and diff in CI.

It also states, per suite, the thing benchmark READMEs usually omit —
**contamination status**: whether the models under test can plausibly have seen
these tasks during training, and what the numbers may therefore mean.

Usage:
  python -m evals.benchmark_manifest            # rewrite BENCHMARK.md
  python -m evals.benchmark_manifest --check    # exit 1 if BENCHMARK.md is stale
"""


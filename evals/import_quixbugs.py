"""Convert QuixBugs into SmallCoder benchmark tasks.

QuixBugs (James Koppel, MIT licence) is 40+ classic algorithms, each carrying a
single realistic defect, with reference fixes and test data. Importing it buys
the one thing this project's own suites cannot: **tasks nobody here authored.**
Every existing fixture was written by the same person for the same project, so
its difficulty is calibrated against nothing.

Three things have to be rebuilt during conversion, because QuixBugs' own layout
is not usable directly:

* Its "correct" programs also delete the trailing docstring, so a raw diff is
  two hunks — the real one-line fix plus documentation noise. Only the code
  change is taken.
* Its tests import through a ``pytest.use_correct`` switch and a shared
  ``load_testdata`` helper that reaches outside the program directory. Each task
  gets a standalone test instead, with its data inlined, so the fixture is
  self-contained.
* The issue text is generated by actually *running* the buggy code on a failing
  case and reporting what it does — including hanging, which several of these
  do. A bug report that says "returns 3, expected 7" is what a user would file;
  restating the docstring is not.

Usage:
  python -m evals.import_quixbugs --source /path/to/QuixBugs
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_FIXTURES = ROOT / "evals" / "quixbugs" / "fixtures"
OUT_TASKS = ROOT / "evals" / "quixbugs" / "tasks"

CONFTEST = "# Empty conftest so pytest puts the repository root on sys.path.\n"


def strip_trailing_docstring(lines: list[str]) -> list[str]:
    """Drop the module-level docstring QuixBugs appends after the code."""
    for i, line in enumerate(lines):
        if line.startswith('"""') and i > 0:
            return lines[:i]
    return lines


def _trim_blank_edges(lines: list[str]) -> list[str]:
    """QuixBugs' reference files carry a leading blank line the buggy ones lack."""
    start, end = 0, len(lines)
    while start < end and not lines[start].strip():
        start += 1
    while end > start and not lines[end - 1].strip():
        end -= 1
    return lines[start:end]


def _is_meaningful(before: list[str], after: list[str]) -> bool:
    """True unless the hunk only moves blank lines or edits comments.

    The reference programs also tidy comments and whitespace, which would
    otherwise make a one-line bug fix look like a multi-hunk rewrite and get the
    task discarded.
    """
    def code_only(lines: list[str]) -> list[str]:
        out = []
        for line in lines:
            code = line.split("#", 1)[0].rstrip()
            if code.strip():
                out.append(code)
        return out

    return code_only(before) != code_only(after)


def find_fix(buggy: str, correct: str) -> tuple[str, str] | None:
    """The code change only, ignoring docstring, comment and whitespace noise.

    Returns (old, new) where `old` occurs exactly once in the buggy source:
    context lines are prepended until it does, because the edit tool under test
    requires a unique anchor. Pure insertions are anchored on the line above.
    """
    b_lines = _trim_blank_edges(strip_trailing_docstring(buggy.splitlines(keepends=True)))
    c_lines = _trim_blank_edges(strip_trailing_docstring(correct.splitlines(keepends=True)))
    ops = [op for op in difflib.SequenceMatcher(None, b_lines, c_lines).get_opcodes()
           if op[0] != "equal" and _is_meaningful(b_lines[op[1]:op[2]], c_lines[op[3]:op[4]])]
    if len(ops) != 1:
        return None
    _, i1, i2, j1, j2 = ops[0]

    for back in range(0, 6):
        start = max(0, i1 - back)
        old = "".join(b_lines[start:i2])
        new = "".join(b_lines[start:i1] + c_lines[j1:j2])
        if old and old != new and buggy.count(old) == 1:
            return old, new
    return None


def _stable_repr(value: object) -> str:
    """Reprs that embed a memory address are not reproducible and must not ship.

    A generator repr like "<generator object flatten at 0x102bf5b60>" would be
    committed into the issue text and differ on every machine.
    """
    return re.sub(r" at 0x[0-9a-fA-F]+", "", repr(value))


def observe_failure(program: Path, name: str, cases: list) -> str | None:
    """Run the buggy function on each case until one misbehaves; describe it.

    ``program`` is the fixture ROOT, which is what goes on sys.path. Using its
    parent instead makes ``import <name>`` resolve to the fixture directory as a
    namespace package, so every task would be described as raising
    "'module' object is not callable" -- a symptom that does not exist, fed to
    the agent as its bug report.
    """
    for args, expected in cases[:12]:
        script = textwrap.dedent(f"""
            import json, sys
            sys.path.insert(0, {str(program)!r})
            from {name} import {name}
            r = {name}(*json.loads({json.dumps(json.dumps(args))}))
            if hasattr(r, "__next__"):
                r = list(r)
            print(json.dumps(r, default=str))
        """)
        try:
            proc = subprocess.run([sys.executable, "-B", "-c", script],
                                  capture_output=True, text=True, timeout=5)
        except subprocess.TimeoutExpired:
            return f"calling it with {args!r} never returns — it hangs"
        if proc.returncode != 0:
            last = (proc.stderr.strip().splitlines() or ["an exception"])[-1]
            return f"calling it with {args!r} raises {last}"
        try:
            got = json.loads(proc.stdout.strip() or "null")
        except json.JSONDecodeError:
            continue
        if got != expected:
            return (f"calling it with {args!r} returns {_stable_repr(got)}, "
                    f"but the answer should be {_stable_repr(expected)}")
    return None


def build_test(name: str, cases: list) -> str:
    return (
        "import pytest\n\n"
        f"from {name} import {name}\n\n\n"
        "CASES = [\n"
        + "".join(f"    ({json.dumps(a)}, {json.dumps(e)}),\n" for a, e in cases)
        + "]\n\n\n"
        '@pytest.mark.parametrize("args,expected", CASES)\n'
        f"def test_{name}(args, expected):\n"
        f"    result = {name}(*args)\n"
        "    if hasattr(result, \"__next__\"):\n"
        "        result = list(result)  # generator; a str is iterable too, do not unwrap it\n"
        "    if isinstance(expected, float):\n"
        "        assert result == pytest.approx(expected, rel=1e-4, abs=1e-4)\n"
        "    else:\n"
        "        assert result == expected\n"
    )


def verify(fixture: Path, old: str, new: str, target: str) -> tuple[bool, bool, bool]:
    """Baseline must fail FAST; the reference fix alone must then make it pass.

    Returns (baseline_fails, fix_passes, baseline_timed_out). A timing-out
    baseline counts as "not passing", but it is not usable: several QuixBugs
    defects loop forever on inputs beyond the first failing one, and the agent
    under test would burn its full command timeout on every `pytest` it runs,
    with the runtime verifying repeatedly. One such task would dominate a sweep,
    so the caller skips it rather than importing it.
    """
    def run(path: Path) -> tuple[bool, bool]:
        try:
            proc = subprocess.run(
                [sys.executable, "-B", "-m", "pytest", "-q", "-p", "no:cacheprovider"],
                cwd=path, capture_output=True, text=True, timeout=60)
        except subprocess.TimeoutExpired:
            return False, True
        return proc.returncode == 0, False

    tmp = fixture.parent / f".check_{fixture.name}"
    shutil.rmtree(tmp, ignore_errors=True)
    shutil.copytree(fixture, tmp)
    try:
        baseline_passes, baseline_timed_out = run(tmp)
        if baseline_timed_out:
            return True, False, True
        src = tmp / target
        src.write_text(src.read_text().replace(old, new, 1), encoding="utf-8")
        fixed_passes, _ = run(tmp)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return (not baseline_passes), fixed_passes, False


def convert(source: Path) -> dict:
    OUT_FIXTURES.mkdir(parents=True, exist_ok=True)
    OUT_TASKS.mkdir(parents=True, exist_ok=True)
    imported, skipped = [], []

    for prog in sorted((source / "python_programs").glob("*.py")):
        name = prog.stem
        correct = source / "correct_python_programs" / f"{name}.py"
        data = source / "json_testcases" / f"{name}.json"
        if not (correct.is_file() and data.is_file()):
            skipped.append((name, "no reference fix or no json test data"))
            continue

        cases = []
        for line in data.read_text().splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            if isinstance(row, list) and len(row) == 2 and isinstance(row[0], list):
                cases.append((row[0], row[1]))
        if len(cases) < 2:
            skipped.append((name, "fewer than two usable test cases"))
            continue

        fix = find_fix(prog.read_text(), correct.read_text())
        if fix is None:
            skipped.append((name, "fix is not a single anchorable replacement"))
            continue
        old, new = fix

        fixture = OUT_FIXTURES / name
        shutil.rmtree(fixture, ignore_errors=True)
        (fixture / "tests").mkdir(parents=True)
        (fixture / "conftest.py").write_text(CONFTEST, encoding="utf-8")
        (fixture / f"{name}.py").write_text(prog.read_text(), encoding="utf-8")
        (fixture / "tests" / f"test_{name}.py").write_text(build_test(name, cases),
                                                           encoding="utf-8")

        symptom = observe_failure(fixture, name, cases)
        if symptom is None:
            shutil.rmtree(fixture, ignore_errors=True)
            skipped.append((name, "buggy program passes its own test data"))
            continue
        if "hangs" in symptom:
            # Realistic, but pathological as a benchmark task: the agent's own
            # `pytest` would burn its full 120s command timeout on every run, and
            # the runtime verifies repeatedly, so one task would dominate a sweep.
            shutil.rmtree(fixture, ignore_errors=True)
            skipped.append((name, "buggy version hangs; tests would time out on every agent step"))
            continue

        baseline_fails, fix_passes, timed_out = verify(fixture, old, new, f"{name}.py")
        if timed_out:
            shutil.rmtree(fixture, ignore_errors=True)
            skipped.append((name, "baseline test suite never finishes; unusable as a task"))
            continue
        if not (baseline_fails and fix_passes):
            shutil.rmtree(fixture, ignore_errors=True)
            skipped.append((name,
                            f"validation failed (fails={baseline_fails}, "
                            f"fixed={fix_passes})"))
            continue

        for cache in fixture.rglob("__pycache__"):
            shutil.rmtree(cache, ignore_errors=True)
        (OUT_TASKS / f"{name}.json").write_text(json.dumps({
            "id": name,
            "category": "QuixBugs (external, MIT): classic algorithm with a single injected defect",
            "fixture": f"evals/quixbugs/fixtures/{name}",
            "issue": f"The {name.replace('_', ' ')} routine gives wrong results: {symptom}.",
            "ground_truth_files": [f"{name}.py"],
            "reference_fix": {"path": f"{name}.py", "old": old, "new": new},
            "max_steps": 30,
            "source": "https://github.com/jkoppel/QuixBugs",
        }, indent=2) + "\n", encoding="utf-8")
        imported.append(name)

    return {"imported": imported, "skipped": skipped}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m evals.import_quixbugs")
    parser.add_argument("--source", required=True, help="path to a QuixBugs checkout")
    args = parser.parse_args(argv)

    result = convert(Path(args.source))
    for name, why in result["skipped"]:
        print(f"[skip] {name}: {why}", flush=True)
    print(f"\n[quixbugs] imported {len(result['imported'])} tasks, "
          f"skipped {len(result['skipped'])}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
